using namespace std; // Стандартное пространство имен

int sumNumbers(int n) { // Функция суммы чисел
    if (n <= 0) { // Проверка числа
        return 0; // Возвращаем ноль
    } // Конец условия
    int sum = 0; // Переменная суммы
    for (int i = 1; i <= n; i++) { // Цикл от 1 до n
        sum += i; // Прибавляем число
    } // Конец цикла
    return sum; // Возвращаем сумму
} // Конец функции

void calculate(int a, int b, int& sum, int& product) { // Функция со ссылками
    sum = a + b; // Записываем сумму в первую ссылку
    product = a * b; // Записываем произведение во вторую ссылку
} // Конец функции

